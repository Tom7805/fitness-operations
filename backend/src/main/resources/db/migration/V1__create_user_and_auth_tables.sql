    ('PERSONAL_TRAINER', 'Huấn luyện viên cá nhân',     FALSE, 50),
    ('GROUP_TRAINER',    'Huấn luyện viên lớp nhóm',    FALSE, 60),
    ('ACCOUNTANT',       'Kế toán',                     FALSE, 70),
